import argparse
import asyncio
from playwright.async_api import async_playwright
import psycopg
from psycopg.types.json import Jsonb
from pgvector.psycopg import register_vector
from langchain_text_splitters import RecursiveCharacterTextSplitter, HTMLHeaderTextSplitter
from bs4 import BeautifulSoup
import uuid
from core.db import DATABASE_URL, sole_client_slug
from core.embeddings import get_ov_embedding

EMBED_BATCH_SIZE = 32  # Chunks embedded per OpenVINO forward pass
# A run still marked 'running' after this long crashed without recording it (the server stopped mid-crawl)
CRAWL_STALE_MINUTES = 30
INTERRUPTED_ERROR = "Interrupted: the server stopped before the crawl finished"

class CrawlAlreadyRunning(Exception):
    pass

# Pages to crawl are managed per client in knowledge_sources. Params: (client_id,)
GET_SOURCES_QUERY = """
    SELECT url, strategy FROM knowledge_sources WHERE client_id = %s AND enabled ORDER BY id
"""

# Params: (slug,)
GET_CLIENT_ID_QUERY = "SELECT id FROM clients WHERE slug = %s"

# Returns no row when a crawl is already running (unique index crawl_runs_one_running). Params: (client_id,)
START_RUN_QUERY = """
    INSERT INTO crawl_runs (client_id, status) VALUES (%s, 'running')
    ON CONFLICT (client_id) WHERE status = 'running' DO NOTHING
    RETURNING id
"""

# Params: (error, client_id, stale_minutes)
FAIL_STALE_RUNS_QUERY = """
    UPDATE crawl_runs SET status = 'failed', finished_at = now(), error = %s
    WHERE client_id = %s AND status = 'running' AND started_at < now() - make_interval(mins => %s)
"""

# Used at server start: crawls started from the dashboard die with the server. Params: (error,)
FAIL_ALL_RUNNING_QUERY = """
    UPDATE crawl_runs SET status = 'failed', finished_at = now(), error = %s WHERE status = 'running'
"""

# Saved after every page so the dashboard can show progress. Params: (pages, crawl_run_id)
SAVE_PAGES_QUERY = """
    UPDATE crawl_runs SET pages = %s WHERE id = %s
"""

# Params: (id, client_id, crawl_run_id, document, metadata, embedding)
INSERT_CHUNK_QUERY = """
    INSERT INTO chunks (id, client_id, crawl_run_id, document, metadata, embedding)
    VALUES (%s, %s, %s, %s, %s, %s)
"""

# Removes chunks from earlier runs once the new run is fully inserted. Params: (client_id, crawl_run_id)
DELETE_OLD_CHUNKS_QUERY = """
    DELETE FROM chunks WHERE client_id = %s AND crawl_run_id <> %s
"""

# Params: (chunk_count, pages, crawl_run_id)
FINISH_RUN_QUERY = """
    UPDATE crawl_runs SET status = 'done', finished_at = now(), chunk_count = %s, pages = %s WHERE id = %s
"""

# Params: (error, pages, crawl_run_id)
FAIL_RUN_QUERY = """
    UPDATE crawl_runs SET status = 'failed', finished_at = now(), error = %s, pages = %s WHERE id = %s
"""

async def fetch_page_content(url, page):
    """Returns (cleaned_html, error). Exactly one of them is empty."""
    try:
        print(f"Crawling {url}...")
        response = await page.goto(url, wait_until="domcontentloaded")
        if response is not None and response.status >= 400:
            return "", f"HTTP {response.status}"
        # Wait a bit extra for any JS rendering
        await page.wait_for_timeout(2000)
        html = await page.content()

        # Parse HTML and extract clean text
        soup = BeautifulSoup(html, "html.parser")

        # Remove script and style elements
        for script in soup(["script", "style", "noscript", "header", "footer", "nav"]):
            script.decompose()

        # We return the cleaned HTML string instead of raw text so the HTML splitter can read the tags
        return str(soup), ""
    except Exception as e:
        print(f"Error crawling {url}: {e}")
        return "", str(e).splitlines()[0][:300] or type(e).__name__

def split_into_chunks(extracted_data):
    """Returns (document, metadata) pairs for every non-empty chunk."""
    chunks_to_store = []

    # 1. HTML-Aware Splitter (Splits by sections/headers)
    headers_to_split_on = [
        ("h1", "Header 1"),
        ("h2", "Header 2"),
    ]
    html_splitter = HTMLHeaderTextSplitter(headers_to_split_on=headers_to_split_on)

    # 2. Fallback Splitter (In case a single section is too massive)
    text_splitter = RecursiveCharacterTextSplitter(
        chunk_size=1000,
        chunk_overlap=200,
        length_function=len,
    )

    for data in extracted_data:
        if data["strategy"] == "html":
            # Step 1: Split by HTML semantics
            header_splits = html_splitter.split_text(data["text"])
            # Step 2: Ensure no chunk is > 1000 chars
            final_chunks = text_splitter.split_documents(header_splits)

            for chunk in final_chunks:
                # Add url to the metadata generated by the HTML splitter
                meta = chunk.metadata
                meta["url"] = data["url"]

                # Avoid empty chunks
                if not chunk.page_content.strip():
                    continue

                chunks_to_store.append((chunk.page_content, meta))

        elif data["strategy"] == "recursive_only":
            # For non-HTML splitting, we must strip the raw HTML tags first
            soup = BeautifulSoup(data["text"], "html.parser")
            clean_text = soup.get_text(separator="\n\n", strip=True)

            chunks = text_splitter.split_text(clean_text)
            for chunk in chunks:
                if not chunk.strip():
                    continue
                chunks_to_store.append((chunk, {"url": data["url"]}))

    return chunks_to_store

def start_run(client_id):
    """Records a new running crawl and returns its id, or None if one is already running."""
    with psycopg.connect(DATABASE_URL, autocommit=True) as conn:
        conn.execute(FAIL_STALE_RUNS_QUERY, (INTERRUPTED_ERROR, client_id, CRAWL_STALE_MINUTES))
        row = conn.execute(START_RUN_QUERY, (client_id,)).fetchone()
    return row[0] if row else None

def fail_interrupted_runs():
    """Called when the server starts, before any crawl can be launched from it."""
    with psycopg.connect(DATABASE_URL, autocommit=True) as conn:
        conn.execute(FAIL_ALL_RUNNING_QUERY, (INTERRUPTED_ERROR,))

async def run_crawl(client_id, run_id=None):
    """Crawls the client's knowledge sources and replaces their chunks. Returns the new chunk count.

    The old chunks stay searchable until the new ones are fully inserted, so the bot never runs without data.
    Pass run_id when start_run() was already called (the dashboard does, to answer the click straight away).
    """
    if run_id is None:
        run_id = start_run(client_id)
        if run_id is None:
            raise CrawlAlreadyRunning("A crawl is already running for this client")
    with psycopg.connect(DATABASE_URL, autocommit=True) as conn:
        sources = conn.execute(GET_SOURCES_QUERY, (client_id,)).fetchall()

    # One entry per URL, shown on the dashboard; chunks is filled in after splitting
    pages = [{"url": url, "strategy": strategy, "ok": None, "chunks": None, "error": None} for url, strategy in sources]
    try:
        if not sources:
            raise RuntimeError("No crawl URLs are turned on")

        with psycopg.connect(DATABASE_URL, autocommit=True) as conn:
            conn.execute(SAVE_PAGES_QUERY, (Jsonb(pages), run_id))

        extracted_data = []
        async with async_playwright() as p:
            browser = await p.chromium.launch(headless=True)
            page = await browser.new_page()

            for entry in pages:
                text, error = await fetch_page_content(entry["url"], page)
                entry.update(ok=bool(text), error=error or None)
                if text:
                    extracted_data.append({"url": entry["url"], "text": text, "strategy": entry["strategy"]})
                with psycopg.connect(DATABASE_URL, autocommit=True) as conn:
                    conn.execute(SAVE_PAGES_QUERY, (Jsonb(pages), run_id))

            await browser.close()

        print("Crawling finished. Chunking and storing in VectorDB...")
        chunks_to_store = split_into_chunks(extracted_data)
        for entry in pages:
            if entry["ok"]:
                entry["chunks"] = sum(1 for _, meta in chunks_to_store if meta["url"] == entry["url"])
        # Keep the previous knowledge rather than wiping it if every page failed (e.g. site down)
        if not chunks_to_store:
            raise RuntimeError("No content extracted from any source")

        # Postgres doesn't embed for us (Chroma did), so compute embeddings here in batches
        rows = []
        for start in range(0, len(chunks_to_store), EMBED_BATCH_SIZE):
            batch = chunks_to_store[start:start + EMBED_BATCH_SIZE]
            embeddings = get_ov_embedding([doc for doc, _ in batch]).numpy()
            for (doc, meta), embedding in zip(batch, embeddings):
                rows.append((uuid.uuid4(), client_id, run_id, doc, Jsonb(meta), embedding))

        # Insert new chunks, drop the old run's and mark the run done in one transaction
        with psycopg.connect(DATABASE_URL) as conn:
            register_vector(conn)
            with conn.cursor() as cur:
                cur.executemany(INSERT_CHUNK_QUERY, rows)
            conn.execute(DELETE_OLD_CHUNKS_QUERY, (client_id, run_id))
            conn.execute(FINISH_RUN_QUERY, (len(rows), Jsonb(pages), run_id))

    except Exception as e:
        with psycopg.connect(DATABASE_URL, autocommit=True) as conn:
            conn.execute(FAIL_RUN_QUERY, (str(e), Jsonb(pages), run_id))
        raise

    print(f"Successfully stored {len(rows)} chunks in Postgres.")
    return len(rows)

if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Crawl a client's website into the vector DB")
    parser.add_argument("--client", help="client slug (default: the only client)")
    args = parser.parse_args()

    with psycopg.connect(DATABASE_URL) as conn:
        try:
            args.client = args.client or sole_client_slug(conn)
        except LookupError as e:
            raise SystemExit(str(e))
        row = conn.execute(GET_CLIENT_ID_QUERY, (args.client,)).fetchone()
    if row is None:
        raise SystemExit(f"Unknown client '{args.client}'. Run seed.py first.")

    try:
        asyncio.run(run_crawl(row[0]))
    except CrawlAlreadyRunning as e:
        raise SystemExit(str(e))
